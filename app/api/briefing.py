"""GET /api/briefing: this week's briefing. Facts always; a written paragraph for a section only when one was generated and passed the check."""
from datetime import date

from fastapi import APIRouter, Depends, HTTPException
from sqlalchemy.orm import Session

from app.briefing import build, monday
from app.db import get_session
from app.llm.briefing import stored
from app.zones import BY_KEY

router = APIRouter()


@router.get("/briefing")
def briefing(zone: str = "willamette", session: Session = Depends(get_session)):
    if zone not in BY_KEY:
        raise HTTPException(422, f"zone must be one of {', '.join(BY_KEY)}")
    today = date.today()
    written = stored(session, monday(today), zone)
    sections = []
    for s in build(session, today, zone):
        w = written.get(s.key) if s.narrate else None
        sections.append({"key": s.key, "title": s.title, "narrated": w is not None,
                         "text": w["text"] if w else None, "as_of": w["as_of"] if w else None, "model": w["model"] if w else None,
                         # a paragraph is shown with the facts it was written from; otherwise the facts as they are now
                         "facts": w["facts"] if w else s.facts})
    return {"week_of": monday(today).isoformat(), "zone": zone, "label": BY_KEY[zone].label, "sections": sections,
            "note": "Written paragraphs are generated by a local model from the facts listed under them and checked against those facts. "
                    "Numbers come from the data, not the model. This page does not state regulations."}
